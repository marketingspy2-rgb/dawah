/** Fields a lesson needs in every language before it can be scheduled. */
export function missingLanguages(lesson: Pick<Lesson, "title" | "point" | "question" | "practice">, langs: Lang[]): Lang[] {
  return langs.filter((l) => ![lesson.title, lesson.point, lesson.question, lesson.practice].every((f) => (f[l] ?? "").trim()));
}
