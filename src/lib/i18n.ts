export const DICTS: Record<UiLang, Dict> = { ar, en };
export type TKey = keyof Dict;

export function translator(lang: UiLang) {
  const d = DICTS[lang];
  return (key: TKey, vars?: Record<string, string | number>) =>
    vars ? d[key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : d[key];
}

